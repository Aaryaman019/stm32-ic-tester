static bool send_cmds(const uint8_t *c, uint16_t n)
{
    return HAL_I2C_Mem_Write(s_i2c, s_addr, 0x00, I2C_MEMADD_SIZE_8BIT, (uint8_t *)c, n, 60) == HAL_OK;
}

static bool s_sh1106;

static bool send_init(bool blankFirst)
{
    static const uint8_t init_sh1106[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0xAD, 0x8B,   /* DC-DC on (SH1106) */
        0x8D, 0x14,                                                   /* charge pump on (SSD1306 clones; ignored by SH1106) */
        0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xFF, 0xD9, 0x1F, 0xDB, 0x40,
        0x33, 0xA6, 0xA4, 0xAF                                        /* pump 9 V, display ON */
    };
    static const uint8_t init_ssd1306[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14,   /* charge pump on */
        0x20, 0x02,                                                   /* page addressing */
        0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40,
        0x2E, 0xA6, 0xA4, 0xAF
    };
    uint8_t skip = blankFirst ? 0u : 1u;                              /* skip 0xAE (display OFF) on re-init: no blink */
    return s_sh1106 ? send_cmds(init_sh1106 + skip, (uint16_t)(sizeof init_sh1106 - skip))
                    : send_cmds(init_ssd1306 + skip, (uint16_t)(sizeof init_ssd1306 - skip));
}

bool oled_begin(I2C_HandleTypeDef *hi2c, uint8_t addr7, bool sh1106)
{
    s_i2c    = hi2c;
    s_addr   = (uint16_t)(addr7 << 1);
    s_sh1106 = sh1106;
    s_coloff = sh1106 ? 2 : 0;
    if (HAL_I2C_IsDeviceReady(s_i2c, s_addr, 3, 10) != HAL_OK) return false;
    oled_clear();
    oled_invalidate();
    if (!send_init(true)) return false;
    oled_flush();
    return true;
}

/* After an I2C bus recovery: re-assert only orientation / normal-display / display-ON (no clock, pump or
 * contrast commands, so the panel does not flicker), keep the framebuffer, redraw everything on next flush. */
bool oled_reinit(void)
{
    static const uint8_t re_sh[]  = { 0x40, 0xA1, 0xC8, 0xA6, 0xA4, 0xAF };
    static const uint8_t re_ssd[] = { 0x40, 0x20, 0x02, 0x8D, 0x14, 0xA1, 0xC8, 0xA6, 0xA4, 0xAF };  /* + page mode, pump */
    oled_invalidate();
    if (!s_i2c) return false;
    return s_sh1106 ? send_cmds(re_sh, sizeof re_sh) : send_cmds(re_ssd, sizeof re_ssd);
}

void oled_clear(void) { memset(fb, 0, sizeof fb); }

static void px(int16_t x, int16_t y)
{
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    fb[x + (y >> 3) * 128] |= (uint8_t)(1u << (y & 7));
}

void oled_text(int16_t x, int16_t y, const char *s, uint8_t size)
{
    if (!s) return;
    for (; *s && x < 128; s++, x += 6 * size) {
        uint8_t c = (uint8_t)*s;
        if (c < 32 || c > 126) c = '?';
        const uint8_t *g = font5x7[c - 32];
        for (uint8_t col = 0; col < 5; col++)
            for (uint8_t row = 0; row < 8; row++)
                if (g[col] & (1u << row))
                    for (uint8_t dx = 0; dx < size; dx++)
                        for (uint8_t dy = 0; dy < size; dy++)
                            px((int16_t)(x + col * size + dx), (int16_t)(y + row * size + dy));
    }
}

void oled_invalidate(void) { memset(shownValid, 0, sizeof shownValid); }
void oled_touch_page(uint8_t page) { shownValid[page & 7u] = false; }

void oled_rect(int16_t x, int16_t y, int16_t w, int16_t h, bool fill)
{
    for (int16_t j = 0; j < h; j++)
        for (int16_t i = 0; i < w; i++)
            if (fill || j == 0 || j == h - 1 || i == 0 || i == w - 1) px((int16_t)(x + i), (int16_t)(y + j));
}

void oled_hline(int16_t x, int16_t y, int16_t w) { for (int16_t i = 0; i < w; i++) px((int16_t)(x + i), y); }

bool oled_flush(void)
{
    bool all = true;
    for (uint8_t page = 0; page < 8; page++) {
        uint8_t *src = &fb[page * 128];
        if (shownValid[page] && !memcmp(src, &shown[page * 128], 128)) continue;   /* unchanged: skip */
        uint8_t c[3] = { (uint8_t)(0xB0 | page), (uint8_t)(s_coloff & 0x0F), (uint8_t)(0x10 | (s_coloff >> 4)) };
        bool ok = send_cmds(c, 3) &&
                  HAL_I2C_Mem_Write(s_i2c, s_addr, 0x40, I2C_MEMADD_SIZE_8BIT, src, 128, 60) == HAL_OK;
        if (ok) memcpy(&shown[page * 128], src, 128);
        shownValid[page] = ok;                                                   /* retry next flush on error */
        if (!ok) all = false;
    }
    return all;
}
